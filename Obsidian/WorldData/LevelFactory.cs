using Microsoft.Extensions.DependencyInjection;
using Obsidian.Plugins;
using Obsidian.Plugins.PluginProviders;
using Obsidian.WorldData.Generators;

namespace Obsidian.WorldData;

public sealed class LevelFactory(IServiceScopeFactory serviceScopeFactory) : ILevelFactory
{
    private static readonly Type[] worldArgTypes = [typeof(ILevelGenerator), typeof(string), typeof(string)];
    private static readonly Type[] dimensionArgTypes = [typeof(ILevelGenerator), typeof(string), typeof(IWorld)];

    private ObjectFactory<World> worldFactory;
    private ObjectFactory<Dimension> dimensionFactory;

    private readonly IServiceScopeFactory serviceScopeFactory = serviceScopeFactory;

    public Dictionary<string, Type> LevelGenerators { get; } = [];

    public IDimension CreateDimension(IWorld parentWorld, string name, string generatorId)
    {
        using var serviceProviderScope = this.serviceScopeFactory.CreateScope();

        var generator = this.CreateGenerator(serviceProviderScope.ServiceProvider, generatorId);

        return this.dimensionFactory.Invoke(serviceProviderScope.ServiceProvider, [generator, name, parentWorld]);
    }

    /// <summary>
    /// Creates a dimension of <paramref name="parentWorld"/> generated by <paramref name="generator"/>, like a plugin's
    /// dimension, whose generator is built from its level stem rather than registered.
    /// </summary>
    internal IDimension CreateDimension(IWorld parentWorld, string name, ILevelGenerator generator)
    {
        using var serviceProviderScope = this.serviceScopeFactory.CreateScope();

        return this.dimensionFactory.Invoke(serviceProviderScope.ServiceProvider, [generator, name, parentWorld]);
    }

    public IWorld CreateWorld(string name, string seed, string generatorId)
    {
        using var serviceProviderScope = this.serviceScopeFactory.CreateScope();

        var generator = this.CreateGenerator(serviceProviderScope.ServiceProvider, generatorId);

        return this.worldFactory.Invoke(serviceProviderScope.ServiceProvider, [generator, name, seed]);
    }

    // A generator the host registered, or else one running the plugin generator of that identifier (see
    // PluginLevelGenerator), which leaves the level stopped while no plugin registers it, rather than generating it
    // with another generator.
    private ILevelGenerator CreateGenerator(IServiceProvider services, string generatorId) =>
        this.LevelGenerators.TryGetValue(generatorId, out var generatorType)
            ? (ILevelGenerator)ActivatorUtilities.CreateInstance(services, generatorType)
            : new PluginLevelGenerator(generatorId);

    public void Initialize()
    {
        this.worldFactory = ActivatorUtilities.CreateFactory<World>(worldArgTypes);
        this.dimensionFactory = ActivatorUtilities.CreateFactory<Dimension>(dimensionArgTypes);

        this.RegisterDefaults();
    }

    /// <summary>
    /// Registers the "obsidian-vanilla" entities and objects.
    /// </summary>
    /// Might be used for more stuff later so I'll leave this here - tides
    private void RegisterDefaults()
    {
        this.RegisterGenerator<SuperflatGenerator>();
        this.RegisterGenerator<MobTestGenerator>();
        this.RegisterGenerator<OverworldGenerator>();
        this.RegisterGenerator<IslandGenerator>();
        this.RegisterGenerator<EmptyWorldGenerator>();
        this.RegisterGenerator<MojangGenerator>();
        this.RegisterGenerator<MojangNetherGenerator>();
        this.RegisterGenerator<MojangEndGenerator>();
    }

    /// <summary>
    /// Registers a world generator by its <see cref="ILevelGenerator.Id"/>. The server's own stay until it stops.
    /// </summary>
    /// <remarks>
    /// A plugin's generator type is registered like
    /// <see cref="API.Plugins.IPluginRegistry.RegisterGenerator{TGenerator}"/> registers it, without its namespace
    /// rule (the first plugin generator with an id keeps it, and the server's own come first), so unloading the
    /// plugin removes it and stops the levels using it until the plugin loads again. Plugins should register theirs
    /// in <c>ConfigureRegistry</c> or their load callbacks, after which the levels waiting for them resume.
    /// </remarks>
    /// <exception cref="InvalidOperationException">
    /// The generator has no id, or it's a plugin's and the plugin is unloading.
    /// </exception>
    public void RegisterGenerator<T>() where T : ILevelGenerator, new()
    {
        var gen = new T();
        if (string.IsNullOrWhiteSpace(gen.Id))
            throw new InvalidOperationException($"Failed to get id for generator: {gen.Id}");

        if (PluginLoadContext.OwnerOf(typeof(T).Assembly) is not PluginContainer plugin)
        {
            this.LevelGenerators.TryAdd(gen.Id, typeof(T));
            return;
        }

        // As with the server's own, the first generator registered with an id keeps it.
        if (PluginGenerators.Find(gen.Id) is not null)
            return;

        PluginGenerators.Register(plugin, gen.Id, typeof(T));

        // Closed before its generators are released, so one registered meanwhile is either released then or here.
        if (plugin.IsClosing)
        {
            PluginGenerators.Release(plugin);
            throw new InvalidOperationException($"{plugin.Info.Name} is unloading.");
        }
    }
}
