"""
Runs the redstone scenarios on the vanilla oracle and writes Obsidian.Tests/Assets/redstone_scenarios.json.

Usage (from the repository root):
    python3 tools/redstone/generate.py [--only NAME ...] [--work DIR] [--out FILE]

The generator needs Java 25+ and the vanilla 1.21.11 server jar, which the asset generator downloads into
Obsidian.AssetGenerator/obj/vanilla/1.21.11. The fixture is committed; tests read it without a server.
"""

from __future__ import annotations

import argparse
import shutil
import json
import time
from pathlib import Path

from scenarios import BOX_Y, FLOOR_Y, ORIGIN_Z, ArrowEvent, Scenario, scenarios
from vanilla_oracle import REPO, VanillaOracle, timed_rows

# Game ticks a save-and-restart runs before the load function freezes the server again (VanillaOracle.save_and_restart).
RELOAD_TICKS = 1
SPAWN_ORIGIN = (-40, ORIGIN_Z)
DEFAULT_OUT = REPO / "Obsidian.Tests" / "Assets" / "redstone_scenarios.json"
DEFAULT_WORK = REPO / "Obsidian.AssetGenerator" / "obj" / "vanilla" / "1.21.11" / "redstone-oracle"
NOTES = (
    "Vanilla 1.21.11 redstone scenarios, generated by tools/redstone/generate.py against a headless vanilla server "
    "(time frozen, one tick stepped per game tick, block states read with execute if block). Coordinates are absolute. "
    "Setup blocks are placed first, live, in order, with neighbor updates (like /setblock). Each tick t from 1 to the "
    "scenario's ticks: its reloads (world saved and server restarted, which runs `ticks` game ticks of its own before the "
    "server is frozen again) and actions happen first, at the previous game time, then the game advances one tick. "
    "Checkpoints hold the box after each tick: one string per (y, z) row, y then z "
    "ascending, with a character per x giving the block's palette index in 0-9a-zA-Z. Palette states are full canonical "
    "states with every property, sorted by name."
)


SETTLE_TICKS = 4


def origin(index: int) -> tuple[int, int]:
    return 32 * index + 8, ORIGIN_Z


def scenario_origin(scenario: Scenario, index: int) -> tuple[int, int]:
    # A reload scenario sits inside the spawn chunks, which the server loads before its first tick. Chunks loaded
    # later race with the one tick a restart runs before its load function freezes the world.
    return (SPAWN_ORIGIN if scenario.reloads else origin(index))


def absolute(local: tuple[int, int, int], base: tuple[int, int]) -> tuple[int, int, int]:
    return base[0] + local[0], local[1], base[1] + local[2]


def absolute_location(local: tuple[float, float, float], base: tuple[int, int]) -> tuple[float, float, float]:
    return base[0] + local[0], local[1], base[1] + local[2]


def run(oracle: VanillaOracle, scenario: Scenario, base: tuple[int, int]) -> dict:
    x0, x1, z0, z1 = scenario.box
    minimum = absolute((x0, BOX_Y[0], z0), base)
    maximum = absolute((x1, BOX_Y[1], z1), base)
    box = [(x, y, z) for y in range(minimum[1], maximum[1] + 1)
           for z in range(minimum[2], maximum[2] + 1) for x in range(minimum[0], maximum[0] + 1)]
    fx0, fx1, fz0, fz1 = scenario.floor

    # Clear the box first: scenarios that reload share the spawn origin, so an earlier scenario can leave blocks behind.
    setup = [(position, "minecraft:air") for position in box]
    setup += [(absolute((x, FLOOR_Y, z), base), "minecraft:stone")
             for x in range(fx0, fx1 + 1) for z in range(fz0, fz1 + 1)]
    setup += [(absolute(local, base), state) for local, state in scenario.setup]
    actions = [(action.tick, absolute(action.pos, base), action.state) for action in scenario.actions]

    # Every block the scenario can place, plus air, is what a position is checked against.
    # Pistons change their own blocks while they move: a base, a head, and the moving piston are all candidates.
    piston_blocks = {"minecraft:piston", "minecraft:sticky_piston", "minecraft:piston_head", "minecraft:moving_piston"}
    candidates = sorted({"minecraft:air"} | piston_blocks | {state.split("[")[0] for _, state in setup}
                        | {state.split("[")[0] for _, _, state in actions})

    loaded_min, loaded_max = (minimum[0] - 1, minimum[2] - 1), (maximum[0] + 1, maximum[2] + 1)
    oracle.force_load(loaded_min, loaded_max)
    # A new force-loaded area finishes loading its chunks asynchronously. Until they are all entity-ticking, a block tick
    # scheduled near them can run a tick late, so the area settles before setup (fixtures are relative to setup).
    for _ in range(SETTLE_TICKS):
        oracle.step()
    for position, state in setup:
        oracle.set_block(position, state)

    reloads_taken: dict[int, int] = {}
    checkpoints = []
    entity_contacts = [{"tick": event.tick, "contacts": [list(absolute(cell, base)) for cell in event.contacts]}
                       for event in scenario.entities]
    arrow_hits = [{"tick": arrow.tick, "block": list(absolute(arrow.block, base)),
                   "location": list(absolute_location(arrow.location, base)), "face": arrow.face}
                  for arrow in scenario.arrows]
    for tick in range(0, scenario.ticks + 1):
        if tick > 0:
            if tick in scenario.reloads:
                advanced = oracle.save_and_restart()
                if advanced != RELOAD_TICKS:
                    raise RuntimeError(f"{scenario.name}: a reload advanced {advanced} ticks, expected {RELOAD_TICKS}")
                reloads_taken[tick] = advanced
            for action_tick, position, state in actions:
                if action_tick == tick:
                    oracle.set_block(position, state)
            for event in scenario.entities:
                if event.tick == tick:
                    if event.kill:
                        oracle.run("kill @e[type=minecraft:armor_stand]")
                    if event.summon is not None:
                        x, y, z = absolute(event.summon, base)
                        oracle.run(f"summon minecraft:armor_stand {x + 0.5} {y} {z + 0.5}")
            for arrow in scenario.arrows:
                if arrow.tick == tick:
                    x, y, z = absolute_location(arrow.origin, base)
                    mx, my, mz = arrow.motion
                    oracle.run(f"summon minecraft:arrow {x} {y} {z} {{Motion:[{mx}d,{my}d,{mz}d]}}")
            oracle.step()

        states = {position: oracle.read_state(position, candidates) for position in box}
        palette, rows = timed_rows(minimum, maximum, states)
        checkpoints.append({"tick": tick, "palette": palette, "rows": rows})

    return {
        "name": scenario.name,
        "description": scenario.description,
        "coverage": scenario.coverage,
        "min": list(minimum),
        "max": list(maximum),
        "setup": [{"pos": list(position), "state": state} for position, state in setup],
        "actions": [{"tick": tick, "pos": list(position), "state": state} for tick, position, state in actions]
        + [{"tick": tick, "reload": True, "ticks": reloads_taken[tick]} for tick in scenario.reloads],
        "entities": entity_contacts,
        "arrows": arrow_hits,
        "checkpoints": checkpoints,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", nargs="*", default=[], help="Scenario names to generate (default: all).")
    parser.add_argument("--work", type=Path, default=DEFAULT_WORK, help="Oracle server work directory.")
    parser.add_argument("--out", type=Path, help="Fixture file to write (required with --only).")
    arguments = parser.parse_args()
    if arguments.only and arguments.out is None:
        parser.error("--only requires --out so a partial generation cannot overwrite the complete fixture")
    output_path = arguments.out or DEFAULT_OUT

    selected = [scenario for scenario in scenarios() if not arguments.only or scenario.name in arguments.only]
    unknown = set(arguments.only) - {scenario.name for scenario in selected}
    if unknown:
        parser.error(f"unknown scenarios: {', '.join(sorted(unknown))}")

    started = time.monotonic()
    results = []
    names = [scenario.name for scenario in scenarios()]
    for scenario in selected:
        scenario_started = time.monotonic()
        # Each scenario gets a fresh world. State left by an earlier scenario changes timing: a reload's scheduled
        # tick moves by one checkpoint, and an arrow hit can be lost. Running every scenario alone keeps the fixture
        # independent of the order and the number of scenarios.
        # The oracle has a rare race (an observer placement once landed a tick late in about one run in six), so every
        # scenario is generated twice and the two runs must agree before the fixture is written.
        attempts = []
        for attempt in range(2):
            isolated = arguments.work / "scenarios" / scenario.name / str(attempt)
            if isolated.exists():
                shutil.rmtree(isolated)
            oracle = VanillaOracle(isolated)
            oracle.prepare()
            oracle.start()
            try:
                attempts.append(run(oracle, scenario, scenario_origin(scenario, names.index(scenario.name))))
            finally:
                oracle.stop()
        if attempts[0] != attempts[1]:
            raise RuntimeError(f"{scenario.name}: two fresh vanilla runs disagree; the scenario is not reproducible")
        results.append(attempts[0])
        print(f"{scenario.name}: {scenario.ticks} ticks in {time.monotonic() - scenario_started:.1f}s", flush=True)

    document = {"_notes": NOTES, "version": "1.21.11", "scenarios": results}
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(document, indent=1) + "\n")
    print(f"Wrote {len(results)} scenarios to {output_path} in {time.monotonic() - started:.1f}s")


if __name__ == "__main__":
    main()
